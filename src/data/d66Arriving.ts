export function getRandomArrivingDescription(
  newPCName: string = 'Новий Персонаж',
  oldPCName: string = 'Загиблий Побратим'
): { roll: string; title: string; text: string } {
  const keys = Object.keys(D66_ARRIVING_ENTRIES);
  const randomKey = keys[Math.floor(Math.random() * keys.length)];
  return getArrivingDescriptionByRoll(randomKey, newPCName, oldPCName);
}

export function getArrivingDescriptionByRoll(
  roll: string,
  newPCName: string = 'Новий Персонаж',
  oldPCName: string = 'Загиблий Побратим'
): { roll: string; title: string; text: string } {
  const entry = D66_ARRIVING_ENTRIES[roll] || D66_ARRIVING_ENTRIES['11'];
  const formattedText = entry.text
    .replace(/\{newPC\}/g, newPCName.trim() || 'Новий Персонаж')
    .replace(/\{oldPC\}/g, oldPCName.trim() || 'Загиблий Побратим');

  return {
    roll: entry.roll,
    title: entry.title,
    text: formattedText,
  };
}
